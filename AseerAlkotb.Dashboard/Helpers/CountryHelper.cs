        public static IEnumerable<SelectListItem> BuildCountrySelectList(string selected = null)
        {
            return Enum.GetValues(typeof(CountryCode))
                .Cast<CountryCode>()
                .Select(c => new SelectListItem
                {
                    Value = c.ToString(), // الكود اللي يتخزن
                    Text = ArabicNames.TryGetValue(c.ToString(), out var name)
                           ? name
                           : c.ToString(), // fallback لو ناقص
                    Selected = !string.IsNullOrWhiteSpace(selected) && selected == c.ToString()
                })
                .OrderBy(i => i.Text);
        }

        public static string ToArabic(string code)
            => ArabicNames.TryGetValue(code ?? "", out var name) ? name : (code ?? "").Replace("_", " ");

